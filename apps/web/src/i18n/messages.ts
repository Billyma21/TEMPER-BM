export const MESSAGES = { fr, nl, en };

export function readLocale(): Locale {
  if (typeof document === 'undefined') return 'fr';
  const match = document.cookie.match(/(?:^|; )temper_locale=(fr|nl|en)/);
  return match?.[1] === 'nl' || match?.[1] === 'en' ? match[1] : 'fr';
}

export function writeLocale(locale: Locale) {
  document.cookie = `temper_locale=${locale}; path=/; max-age=31536000; samesite=lax`;
}

export function localeTag(locale: Locale): string {
  if (locale === 'nl') return 'nl-BE';
  if (locale === 'en') return 'en-BE';
  return 'fr-BE';
}
