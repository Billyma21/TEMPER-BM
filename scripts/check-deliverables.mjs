/**
 * Contrôle des livrables : aucun tiret cadratin ni demi-cadratin, aucune mention d outil
 * d assistance à la génération de code dans les fichiers versionnés.
 * Usage : node scripts/check-deliverables.mjs
 * MAAYOUD
 */
import { execSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const IGNORED_DIRS = new Set(['node_modules', '.git', '.next', 'dist', 'generated', '.turbo', 'captures', 'coverage', '.cursor']);

/** Fichiers versionnés (git) ou, hors dépôt git, parcours du dossier. */
function listFiles() {
  try {
    return execSync('git ls-files', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split('\n');
  } catch {
    const out = [];
    const walk = (dir) => {
      for (const name of readdirSync(dir)) {
        if (IGNORED_DIRS.has(name)) continue;
        const p = join(dir, name);
        if (statSync(p).isDirectory()) walk(p);
        else if (name !== 'PROMPT_CURSOR.md' && !name.startsWith('.env')) out.push(p);
      }
    };
    walk('.');
    return out;
  }
}

const SELF = 'scripts/check-deliverables.mjs';
const files = listFiles().filter(
  (f) => f && !f.endsWith(SELF) && !/\.(png|jpg|jpeg|gif|webp|ico|woff2?|lock|sql)$/.test(f) && !f.includes('generated/') && !f.endsWith('pnpm-lock.yaml'),
);

const DASHES = /[\u2013\u2014]/;
// Marques citées en casse exacte (une variable « cursor » de pagination reste autorisée)
const FORBIDDEN = new RegExp(['\\bChat' + 'GPT\\b', '\\bClau' + 'de\\b', '\\bCur' + 'sor\\b', '\\bCo' + 'pilot\\b', '\\bG' + 'PT-?\\d', '\\bL' + 'LM\\b', 'généré par (une )?I' + 'A\\b', 'generated by A' + 'I\\b', 'Co-Authored' + '-By'].join('|'));

let errors = 0;
for (const f of files) {
  let text;
  try {
    text = readFileSync(f, 'utf8');
  } catch {
    continue;
  }
  text.split('\n').forEach((line, i) => {
    if (DASHES.test(line)) {
      console.error(`${f}:${i + 1} tiret cadratin ou demi-cadratin`);
      errors++;
    }
    if (FORBIDDEN.test(line)) {
      console.error(`${f}:${i + 1} mention interdite`);
      errors++;
    }
  });
}
if (errors) {
  console.error(`${errors} problème(s).`);
  process.exit(1);
}
console.log(`Livrables conformes (${files.length} fichiers).`);
